"""Составление запросов, которые задаются нейросетям и поиску.

Спрашиваем так, как спросил бы клиент: не «ООО Белый Клык», а
«куда пойти лечить зубы в Москве». Если спросить название компании,
нейросеть просто перескажет, что о ней знает, — а нам нужно понять,
всплывает ли она сама, когда её не называли.
"""

# Заготовки под род занятий. Ключ — слово из отрасли, значение —
# как об этом спрашивают люди.
SHAPES = {
    'стоматология': ['стоматология', 'лечение зубов', 'имплантация зубов', 'детский стоматолог'],
    'медицина': ['медицинский центр', 'частная клиника', 'приём врача'],
    'ремонт и отделка': ['ремонт квартиры под ключ', 'отделка квартиры', 'бригада для ремонта'],
    'строительство': ['строительство дома', 'строительная компания', 'подрядчик для стройки'],
    'автосервис': ['автосервис', 'ремонт автомобиля', 'шиномонтаж'],
    'ресторан, кафе и доставка еды': ['ресторан', 'доставка еды', 'где вкусно поесть'],
    'гостиница': ['гостиница', 'где остановиться'],
    'розничный магазин': ['магазин', 'где купить'],
    'оптовая торговля': ['оптовый поставщик', 'где закупать оптом'],
    'бытовые услуги': ['салон красоты', 'парикмахерская', 'бытовые услуги'],
    'спорт и фитнес': ['фитнес-клуб', 'спортзал'],
    'обучение': ['курсы', 'обучение', 'школа'],
    'юридические услуги': ['юрист', 'юридическая помощь'],
    'реклама и маркетинг': ['маркетинговое агентство', 'продвижение бизнеса'],
    'разработка программ': ['разработка сайта', 'ИТ-подрядчик'],
    'недвижимость': ['агентство недвижимости', 'риелтор'],
    'перевозки': ['грузоперевозки', 'доставка груза'],
    'туризм': ['турагентство', 'куда поехать отдыхать'],
    'ремонт техники': ['ремонт техники', 'мастер по ремонту'],
}

# Вопросы, которые люди задают нейросети. %s — род занятий с городом.
# Через двоеточие, а не «Посоветуй стоматологию»: склонять род
# занятий и город по-русски пришлось бы отдельной библиотекой, а так
# фраза остаётся грамотной при любом подставленном слове.
PATTERNS = [
    'Посоветуй, куда обратиться: %s',
    'Какие компании оказывают услуги: %s',
    'Назови лучшие компании: %s',
    'Где сделать недорого: %s',
    'Кому можно доверить: %s',
    'Назови проверенные компании: %s',
    'Что выбрать: %s',
]


def shapes_for(industry, kind):
    """Подбирает, как спрашивают про этот род занятий."""
    industry = (industry or '').lower()
    for key, items in SHAPES.items():
        if key in industry or industry in key:
            return list(items)

    # Ничего не подошло — берём название вида деятельности из ОКВЭД
    # как есть. Формулировка выйдет казённой, но запрос осмысленным.
    base = (kind or industry or '').strip().lower()
    return [base] if base else []


def build(company, limit=12):
    """Возвращает список запросов вида «стоматология в Москве»."""
    city = (company.get('city') or '').strip()
    shapes = shapes_for(company.get('industry'), company.get('kind'))
    if not shapes:
        return []

    with_city = []
    for sh in shapes:
        with_city.append('%s, %s' % (sh, city) if city else sh)

    out = []
    for i, pattern in enumerate(PATTERNS):
        for j, subject in enumerate(with_city):
            if (i + j) % 2 == 0 or len(with_city) == 1:
                out.append(pattern % subject)
    # Порядок: сначала самые обычные вопросы
    seen, uniq = set(), []
    for q in out:
        if q not in seen:
            seen.add(q)
            uniq.append(q)
    return uniq[:limit]


def search_queries(company, limit=6):
    """Запросы для обычного поиска: там пишут не вопросами, а коротко."""
    city = (company.get('city') or '').strip()
    shapes = shapes_for(company.get('industry'), company.get('kind'))
    out = []
    for sh in shapes:
        out.append('%s %s' % (sh, city) if city else sh)
    return out[:limit]
