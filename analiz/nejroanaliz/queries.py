def _rovno(text):
    """Одинаковое написание для сравнения.

    «Онлайн-магазин» и «онлайн магазин» — одно и то же слово, но для
    программы это разные строки. Менеджер пишет как придётся, и на
    дефисе проверка однажды уехала в безликий «розничный магазин»:
    тема не опозналась, вопросов вышло семь вместо двенадцати.
    """
    return ' '.join((text or '').replace('-', ' ').lower().split())


def topic_of(text):
    """Тема по словам-приметам. Пустая строка — тема неизвестна."""
    t = _rovno(text)
    if len(t) < 3:
        return ''
    for topic, words in TRIGGERS:
        for w in words:
            if _rovno(w) in t:
                return topic
    return ''


# Слова, которыми начинается род занятий, и чем их можно заменить.
# «Онлайн-магазин сантехники» -> «магазин сантехники», «доставка
# сантехники», «продажа сантехники». Хвост остаётся в родительном
# падеже, меняется только голова — по-русски выходит грамотно, и
# склонять ничего не нужно.
#
# Так мы получаем несколько разных вопросов про одно и то же дело.
# Спрашивать двенадцать раз одной фразой бессмысленно: нейросеть
# двенадцать раз ответит одинаково.
GOLOVY = {
    'магазин': ('магазин', 'доставка', 'продажа'),
    'интернет магазин': ('интернет-магазин', 'магазин', 'доставка'),
    'онлайн магазин': ('онлайн-магазин', 'магазин', 'доставка'),
    'интернет-магазин': ('интернет-магазин', 'магазин', 'доставка'),
    'онлайн-магазин': ('онлайн-магазин', 'магазин', 'доставка'),
    'доставка': ('доставка', 'магазин', 'продажа'),
    'продажа': ('продажа', 'магазин', 'доставка'),
    'поставщик': ('поставщик', 'продажа', 'доставка'),
    'ремонт': ('ремонт', 'отделка'),
    'установка': ('установка', 'монтаж'),
    'монтаж': ('монтаж', 'установка'),
    'изготовление': ('изготовление', 'производство'),
    'производство': ('производство', 'изготовление'),
}

# Заготовки, которые описывают не рынок, а способ торговли. Спросить
# «интернет-магазин, Москва» — всё равно что не спросить ничего: в
# ответ пойдут Озон и ВкусВилл, кто угодно. Годятся, только когда от
# менеджера вообще нет слов и приходится брать хоть что-то из ОКВЭД.
PUSTYE = ('интернет-магазин', 'розничный магазин', 'оптовая торговля')


def _narrow_subjects(phrase):
    """Из «строительство деревянных домов и бань» делает три запроса:
    саму фразу, «строительство деревянных домов» и «строительство бань».

    Клиент ищет что-то одно, а не оба сразу, и нейросеть по длинной
    фразе с «и» отвечает про что-нибудь одно наугад. Общее слово
    берём первое: после него в русском идёт родительный падеж, и
    «строительство бань» остаётся грамотным без склонения.
    """
    p = ' '.join((phrase or '').split())
    if not p:
        return []
    out = [p]

    words = _rovno(p).split(' ')
    if len(words) < 2:
        return out

    # Голова бывает из двух слов: «интернет магазин», «онлайн магазин».
    # Берём длинную, если такая знакома, иначе первое слово.
    head, rest = words[0], ' '.join(words[1:])
    if len(words) > 2:
        para = ' '.join(words[:2])
        if para in GOLOVY:
            head, rest = para, ' '.join(words[2:])
    parts = [x.strip(' ,') for x in rest.split(' и ')]
    parts = [x for x in parts if len(x) >= 4]
    if len(parts) < 2:
        parts = [rest]
    elif len(parts) >= 2:
        for x in parts:
            q = '%s %s' % (head, x)
            if q not in out:
                out.append(q)

    # Та же тема другими словами: меняем только первое слово.
    # Сравниваем по «ровному» написанию, иначе «онлайн магазин» и
    # «онлайн-магазин» уйдут в список как две разные темы и один и
    # тот же вопрос будет задан дважды.
    def est_uzhe(q):
        return any(_rovno(q) == _rovno(e) for e in out)

    for zamena in GOLOVY.get(head, ()):
        for x in parts:
            q = '%s %s' % (zamena, x)
            if not est_uzhe(q):
                out.append(q)
    return out


def subjects_for(company):
    """Два набора запросов: чем компания занимается на самом деле и
    рынок вообще.

    Менеджер вписывает в заявку слова клиента — «строительство
    деревянных домов и бань». Раньше мы по слову «строит» брали общую
    заготовку «строительство дома», а узкие слова выбрасывали: в
    ответе оказывались домостроительные комбинаты, и выходило, что
    компанию никто не называет. Теперь слова из заявки идут первыми и
    занимают большую часть вопросов, а общая заготовка остаётся
    второй — по ней видно, знают ли компанию на широком рынке.

    Из реестра слова берём иначе. «Строительство жилых и нежилых
    зданий» — это язык ОКВЭД, клиент так не спрашивает, и резать эту
    фразу пополам нельзя: получится «строительство жилых». Там
    спрашиваем общими словами, а саму строчку ОКВЭД берём, только
    если тему не узнали совсем.
    """
    industry, kind = company.get('industry'), company.get('kind')
    own = ' '.join((kind or industry or '').split()).lower().strip(' .,;')

    # Запросы из расширенной анкеты. Это слова, которыми клиент сам
    # описывает, как его ищут, — точнее них нет ничего: ни заготовка
    # по отрасли, ни строчка ОКВЭД так не спросят. Поэтому они идут
    # первыми и занимают начало списка вопросов.
    iz_ankety = [' '.join(str(q).split()).lower().strip(' .,;')
                 for q in (company.get('own_queries') or [])]
    iz_ankety = [q for q in iz_ankety if len(q) >= 3]

    topic = topic_of(industry) or topic_of(kind)
    wide = list(SHAPES.get(topic, [])) if topic else []

    if len(own) < 3:
        return iz_ankety, wide

    if company.get('kind_from_lead'):
        narrow = _narrow_subjects(own)
        # Слова клиента точнее любой заготовки про способ торговли.
        if topic in PUSTYE:
            wide = []
    elif topic:
        narrow = []
    else:
        narrow = [own]

    # Слова из анкеты впереди наших, повторы убираем.
    narrow = iz_ankety + [n for n in narrow if n not in iz_ankety]
    wide = [w for w in wide if w not in narrow]
    return narrow, wide


# Приписка к каждому вопросу. Без неё нейросеть часто отвечает
# советом — «обратитесь в местные цветочные салоны», — и в ответе
# нет ни одного названия. Такой ответ не значит, что компанию не
# знают: её просто не спрашивали назвать. Просим список явно.
ASK_TAIL = ' Ответь списком: пять конкретных компаний с названиями, без пояснений.'


def build(company, limit=12):
    """Возвращает список запросов вида «строительство бань, Москва»."""
    city = (company.get('city') or '').strip()
    narrow, wide = subjects_for(company)
    if not narrow and not wide:
        return []

    patterns = patterns_for(company.get('kind') or company.get('industry'))

    def ask(subjects, want, mesto):
        """Сначала первый вопрос ко всем темам, потом второй ко всем:
        так каждая тема успевает прозвучать, даже если вопросов мало."""
        out = []
        for pattern in patterns:
            for sub in subjects:
                q = pattern % ('%s, %s' % (sub, mesto) if mesto else sub)
                if q not in out:
                    out.append(q)
                if len(out) >= want:
                    return out
        return out

    # Район из анкеты. Четверть вопросов задаём про него: людей
    # интересует то, что рядом с домом, и по району нейросеть нередко
    # называет совсем другие компании, чем по городу целиком.
    rajon = ([r for r in (company.get('rajony') or []) if r] or [''])[0]
    mesto_rajona = ' '.join(x for x in (rajon, city) if x) if rajon else ''
    n_rajon = max(1, int(round(limit * 0.25))) if mesto_rajona else 0
    osnovnyh = limit - n_rajon

    if not narrow:
        out = ask(wide, osnovnyh, city)
    else:
        # Две трети вопросов — про то, чем компания занимается на самом
        # деле, треть — про рынок вообще.
        n_narrow = osnovnyh if not wide else max(1, int(round(osnovnyh * 0.7)))
        out = ask(narrow, n_narrow, city)
        left = osnovnyh - len(out)
        if left > 0 and wide:
            out += [q for q in ask(wide, left, city) if q not in out][:left]

    if n_rajon:
        temy = narrow or wide
        out += [q for q in ask(temy, n_rajon, mesto_rajona) if q not in out][:n_rajon]
    return out[:limit]


def search_queries(company, limit=6):
    """Запросы для обычного поиска: там пишут не вопросами, а коротко."""
    city = (company.get('city') or '').strip()
    rajon = ([r for r in (company.get('rajony') or []) if r] or [''])[0]
    narrow, wide = subjects_for(company)
    out = []
    for sub in narrow + wide:
        q = '%s %s' % (sub, city) if city else sub
        if q not in out:
            out.append(q)
    # Один запрос по району: место в выдаче «рядом» ближе к правде,
    # чем место по городу целиком.
    if rajon and narrow + wide:
        q = ' '.join(x for x in ((narrow + wide)[0], rajon, city) if x)
        if q not in out:
            out.insert(1, q)
    return out[:limit]
