#!/bin/sh
# =========================================================
# Управление ботом на хостинге.
#
#   sh bot.sh start    запустить
#   sh bot.sh stop     остановить
#   sh bot.sh status   жив ли
#   sh bot.sh log      последние строки
#   sh bot.sh cron     поднять, если упал (для расписания)
#
# Бот не открывает никаких портов и ничего не слушает: он сам
# ходит наружу и забирает сообщения. Ограничение хостинга на порты
# выше 1024 к нему поэтому не относится.
# =========================================================

DIR=$(cd "$(dirname "$0")/.." && pwd)
PID="$DIR/bot.pid"
LOG="$DIR/bot.log"
PY="$DIR/venv/bin/python"

zhiv() {
  [ -f "$PID" ] || return 1
  p=$(cat "$PID" 2>/dev/null)
  [ -n "$p" ] || return 1

  # Номера процесса мало по двум причинам.
  #
  # Первая: «kill -0» отвечает «жив» и про мёртвый процесс, которого
  # система ещё не убрала. Расписание тогда решает, что поднимать
  # нечего, и бот молчит до утра.
  #
  # Вторая: после перезагрузки тот же номер достаётся чужому
  # процессу. Проверка по номеру считала бы его нашим ботом, и тот
  # не поднялся бы уже никогда.
  #
  # Поэтому смотрим, чем этот процесс на самом деле занят.
  if [ -r "/proc/$p/cmdline" ]; then
    tr '\0' ' ' < "/proc/$p/cmdline" 2>/dev/null | grep -q 'bot\.py' || return 1
    grep -q '^State:.*Z' "/proc/$p/status" 2>/dev/null && return 1
    return 0
  fi
  kill -0 "$p" 2>/dev/null
}

# Ищем работающего бота из этой же папки, не заглядывая в файл с
# номером. Файл теряется: его можно стереть, перепутать, он остаётся
# от прошлой установки. А запустить второго бота на том же токене
# нельзя ни в коем случае: два бота забирают сообщения по очереди,
# каждый видит половину, и менеджер не получает ответа на свой ИНН.
najti() {
  for d in /proc/[0-9]*; do
    [ -r "$d/cmdline" ] || continue
    tr '\0' ' ' < "$d/cmdline" 2>/dev/null | grep -q "$DIR/bot.py" || continue
    grep -q '^State:.*Z' "$d/status" 2>/dev/null && continue
    echo "${d#/proc/}"
    return 0
  done
  return 1
}

posle_zapuska() {
  # Строки, которые бот написал с последнего запуска. В журнал перед
  # каждым запуском ставится черта, по ней и отрезаем: иначе хвост
  # журнала мешает свежие строки с прошлым разом, и не понять, где
  # чьи. Журнал от прежней версии черты не знает — тогда просто хвост.
  [ -f "$LOG" ] || return 0
  if grep -q '^===== запуск ' "$LOG" 2>/dev/null; then
    stroka=$(grep -n '^===== запуск ' "$LOG" | tail -n 1 | cut -d: -f1)
    tail -n +"$((stroka + 1))" "$LOG"
  else
    tail -n 6 "$LOG"
  fi
}

start() {
  if zhiv; then
    echo "Бот уже работает, номер процесса $(cat "$PID")."
    return 0
  fi

  # Файл с номером мог потеряться, а бот при этом жив.
  chuzhoj=$(najti) || chuzhoj=""
  if [ -n "$chuzhoj" ]; then
    echo "$chuzhoj" > "$PID"
    echo "Бот уже работает, номер процесса $chuzhoj."
    echo "(файл с номером потерялся, записал заново)"
    return 0
  fi
  if [ ! -x "$PY" ]; then
    echo "Нет окружения. Запустите установку заново."
    return 1
  fi
  # Журнал не должен расти бесконечно: на общем хостинге место
  # ограничено, а бот пишет каждую проверку.
  if [ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 5000000 ]; then
    mv "$LOG" "$LOG.staryj"
  fi
  cd "$DIR" || return 1
  # Черта в журнале перед каждым запуском. Без неё последние строки
  # журнала мешаются с прошлым разом: после перезапуска видно три
  # свежие строки и три старых, и нельзя понять, где чьи.
  {
    echo
    echo "===== запуск $(date '+%d.%m.%Y, %H:%M') ====="
  } >> "$LOG"
  # nohup, чтобы бот пережил закрытие Shell-клиента в панели.
  PYTHONUNBUFFERED=1 nohup "$PY" "$DIR/bot.py" >> "$LOG" 2>&1 &
  echo $! > "$PID"
  sleep 3
  if zhiv; then
    echo "Бот запущен, номер процесса $(cat "$PID")."
    # Показываем всё, что бот написал с этого запуска, а не последние
    # шесть строк подряд: подпись «первые строки журнала» врала —
    # это был хвост файла вперемешку с прошлым разом.
    echo "Что он написал при запуске:"
    posle_zapuska | sed 's/^/  /'
  else
    echo "Бот не поднялся. Что в журнале:"
    tail -n 20 "$LOG" | sed 's/^/  /'
    rm -f "$PID"
    return 1
  fi
}

stop() {
  # Останавливаем по файлу, а если он потерялся — по найденному
  # процессу: иначе бот остался бы работать, а мы бы об этом не знали.
  nomer=""
  zhiv && nomer=$(cat "$PID")
  [ -z "$nomer" ] && nomer=$(najti 2>/dev/null || true)

  if [ -n "$nomer" ]; then
    kill "$nomer" 2>/dev/null
    sleep 2
    kill -0 "$nomer" 2>/dev/null && kill -9 "$nomer" 2>/dev/null
    echo "Остановлен."
  else
    echo "Бот и так не работает."
  fi
  rm -f "$PID"
}

case "$1" in
  start)  start ;;
  stop)   stop ;;
  restart) stop; start ;;
  status)
    if zhiv; then
      echo "Работает, номер процесса $(cat "$PID")."
      echo "С последнего запуска:"
      posle_zapuska | tail -n 8 | sed 's/^/  /'
    else
      echo "НЕ работает."
      [ -f "$LOG" ] && echo "Последнее из журнала:" && tail -n 10 "$LOG" | sed 's/^/  /'
    fi
    ;;
  log)    tail -n "${2:-40}" "$LOG" 2>/dev/null || echo "Журнала пока нет." ;;
  cron)
    # Молча поднимаем упавшего. Ставится в расписание раз в пять
    # минут: ночью рвётся связь, процесс может умереть, и поднять
    # его некому — на хостинге нет службы, которая следит за этим.
    zhiv || start >> "$LOG" 2>&1
    ;;
  *)
    echo "Как пользоваться: sh bot.sh start|stop|restart|status|log|cron"
    exit 1
    ;;
esac
